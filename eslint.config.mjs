import { defineConfig } from 'eslint/config';
import tseslint from 'typescript-eslint';
import reactHooks from 'eslint-plugin-react-hooks';
import nextPlugin from '@next/eslint-plugin-next';

/**
 * `next lint` was removed in Next 16, so `npm run lint` now calls ESLint directly.
 *
 * Deliberately NOT built on `eslint-config-next`: it pulls in `eslint-plugin-react`,
 * whose peer range stops at ESLint ^9.7, and this repo is on ESLint 10. This is
 * typescript-eslint's recommended set, the two React hooks rules and Next's own
 * plugin (the source files already carry `@next/next/*` disable comments).
 * Revisit if `eslint-config-next` gains ESLint 10 support.
 *
 * Only TypeScript is linted. The Electron entry points (main.js, preload.js, the
 * printer SDK bridges) are CommonJS and would need their own environment config.
 *
 * SEVERITY POLICY: `error` is reserved for things that are bugs (rules of hooks,
 * parse errors) so `npm run lint` can be a gate. Style-level findings that the
 * codebase already has in bulk are `warn`, so they stay visible without blocking:
 * a lint that reports ~2,500 errors on day one would just be ignored. Do not
 * promote one to `error` without first clearing its existing warnings.
 */
export default defineConfig(
  {
    ignores: [
      '**/node_modules/**',
      '**/.next/**',
      '**/.next-test/**',
      '**/dist/**',
      '**/out/**',
      '**/build/**',
      '**/coverage/**',
      '**/test-results/**',
      '**/playwright-report/**',
      // Sibling checkouts of this repo, not part of this tree.
      '.claude/**',
      '.worktrees/**',
      // JavaScript is not linted (see above).
      '**/*.{js,cjs,mjs}',
      // Generated by `next build`.
      'next-env.d.ts',
    ],
  },
  ...tseslint.configs.recommended,
  {
    files: ['**/*.{ts,tsx}'],
    plugins: { 'react-hooks': reactHooks, '@next/next': nextPlugin },
    rules: {
      ...nextPlugin.configs.recommended.rules,
      'react-hooks/rules-of-hooks': 'error',
      'react-hooks/exhaustive-deps': 'warn',

      // The codebase uses `any` pervasively (raw mysql2 rows, request bodies); ~2,160
      // occurrences. Not a rule this project follows, so it is off rather than noise.
      '@typescript-eslint/no-explicit-any': 'off',

      // Visible, not blocking (see SEVERITY POLICY).
      '@typescript-eslint/no-unused-vars': ['warn', { argsIgnorePattern: '^_', varsIgnorePattern: '^_' }],
      '@typescript-eslint/no-require-imports': 'warn',
      '@typescript-eslint/no-unsafe-function-type': 'warn',
      'prefer-const': 'warn',
    },
  },
);
